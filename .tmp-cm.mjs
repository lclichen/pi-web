import { mkdtemp, writeFile, readFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createJiti } from "jiti";
const jiti = createJiti(import.meta.url, { tsconfigPaths: true });
const m = await jiti.import("./lib/codemode-settings.ts");
const dir = await mkdtemp(join(tmpdir(), "cm-"));
const p = join(dir, "settings.json");
await writeFile(p, JSON.stringify({ defaultModel: "m", defaultTools: ["+grep"] }));
await m.writeCodemodePreference("always", p);
const before = await readFile(p, "utf8");
await writeFile(p, before.replace(/\n\s*/g, ""));
const compact = await readFile(p, "utf8");
console.log("before", JSON.stringify(before));
console.log("compact", JSON.stringify(compact), compact.length);
console.log("read pref", await m.readCodemodePreference(p));
await m.writeCodemodePreference("always", p);
const after = await readFile(p, "utf8");
console.log("equal", after === compact, "afterlen", after.length, JSON.stringify(after));
