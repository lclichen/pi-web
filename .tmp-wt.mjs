import { execFile } from "node:child_process";
import { mkdtemp, mkdir, writeFile, rm } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { promisify } from "node:util";
import { createJiti } from "jiti";
const exec = promisify(execFile);
const tmp = await mkdtemp(path.join(os.tmpdir(), "wt-"));
const repo = path.join(tmp, "repo"), linked = path.join(tmp, "linked");
await exec("git", ["init", repo]);
await exec("git", ["-C", repo, "config", "user.name", "t"]);
await exec("git", ["-C", repo, "config", "user.email", "t@t"]);
await writeFile(path.join(repo, "README.md"), "x\n");
await exec("git", ["-C", repo, "add", "README.md"]);
await exec("git", ["-C", repo, "commit", "-m", "init"]);
await exec("git", ["-C", repo, "worktree", "add", "-b", "feature/test", linked]);
const jiti = createJiti(import.meta.url);
const { resolveProject, listWorktrees } = await jiti.import("./lib/worktree.ts");
console.log("main", await resolveProject(repo + path.sep));
console.log("linked", await resolveProject(linked));
console.log("list", await listWorktrees(linked));
await rm(tmp, { recursive: true, force: true });
